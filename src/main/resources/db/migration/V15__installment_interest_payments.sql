ALTER TABLE installments DROP CONSTRAINT installments_status_check;
ALTER TABLE installments ADD CONSTRAINT installments_status_check
    CHECK (status IN ('UNPAID', 'INTEREST_PAID', 'PAID'));

CREATE TABLE installment_interest_payments
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installment_id  BIGINT        NOT NULL REFERENCES installments (id) ON DELETE CASCADE,
    pay_date        DATE          NOT NULL,
    amount          NUMERIC(14,2) NOT NULL,
    paid_at         TIMESTAMP     NOT NULL
);

CREATE INDEX ix_installment_interest_payments_installment_id ON installment_interest_payments (installment_id);
